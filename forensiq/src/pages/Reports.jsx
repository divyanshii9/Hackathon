import { useMemo, useState } from "react";
import {
  FileText,
  Download,
  CalendarDays,
  MapPin,
  FileCheck,
  Search,
  Eye,
  X,
  ShieldCheck,
  AlertTriangle,
  ClipboardList,
  Filter,
  TreePine
} from "lucide-react";

import { incidents } from "../data/forestData";
import "./Reports.css";

function Reports() {
  const [search, setSearch] = useState("");
  const [statusFilter, setStatusFilter] = useState("All");
  const [riskFilter, setRiskFilter] = useState("All");
  const [selectedReport, setSelectedReport] = useState(null);

  const reports = useMemo(() => {
    return incidents.map((incident, index) => ({
      id: `RPT-${String(index + 1).padStart(3, "0")}`,
      title: `${incident.location} Disturbance Report`,
      incident: incident.id,
      location: incident.location,
      date: incident.date,
      area: incident.area,
      risk: incident.risk,
      status:
        incident.status === "Under Investigation"
          ? "Ready"
          : "Draft",
      investigationStatus: incident.status,
      latitude: incident.latitude,
      longitude: incident.longitude
    }));
  }, []);

  const filteredReports = reports.filter((report) => {
    const matchesSearch =
      report.id.toLowerCase().includes(search.toLowerCase()) ||
      report.incident.toLowerCase().includes(search.toLowerCase()) ||
      report.location.toLowerCase().includes(search.toLowerCase());

    const matchesStatus =
      statusFilter === "All" || report.status === statusFilter;

    const matchesRisk =
      riskFilter === "All" || report.risk === riskFilter;

    return matchesSearch && matchesStatus && matchesRisk;
  });

  const readyCount = reports.filter(
    (report) => report.status === "Ready"
  ).length;

  const draftCount = reports.filter(
    (report) => report.status === "Draft"
  ).length;

  const highRiskCount = reports.filter(
    (report) => report.risk === "High"
  ).length;

  const downloadReport = (report) => {
    const content = `
FORENSIQ
FOREST DISTURBANCE INVESTIGATION REPORT

================================================

REPORT INFORMATION

Report ID: ${report.id}
Incident ID: ${report.incident}
Location: ${report.location}
Detection Date: ${report.date}

================================================

DISTURBANCE DETAILS

Affected Area: ${report.area} hectares
Risk Priority: ${report.risk}
Report Status: ${report.status}
Investigation Status: ${report.investigationStatus}

================================================

LOCATION INFORMATION

Latitude: ${report.latitude ?? "Not available"}
Longitude: ${report.longitude ?? "Not available"}

================================================

INITIAL OBSERVATION

A forest disturbance record has been registered
for the above location.

The incident has been assigned a ${report.risk.toLowerCase()}
risk priority for investigation and review.

================================================

INVESTIGATION REQUIREMENTS

1. Review the reported disturbance location.
2. Examine available satellite imagery.
3. Verify the affected area.
4. Check available forest clearance records.
5. Conduct manual verification by authorised officers.

================================================

IMPORTANT DISCLAIMER

This report is generated using demonstration data.

Risk priority indicates investigation urgency only.
It does not establish illegal forest activity.

All observations require verification by
authorised personnel.

================================================

Generated by FORENSIQ
Forest Investigation and Evidence Intelligence Platform
    `;

    const blob = new Blob([content], {
      type: "text/plain"
    });

    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");

    link.href = url;
    link.download = `${report.id}.txt`;

    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);

    URL.revokeObjectURL(url);
  };

  return (
    <div className="reports-page">

      {/* HEADER */}

      <div className="reports-heading">
        <div>
          <div className="reports-heading-label">
            <TreePine size={16} />
            FOREST INVESTIGATION MANAGEMENT
          </div>

          <h1>Investigation Reports</h1>

          <p>
            Review, manage and export forest disturbance investigation records.
          </p>
        </div>

        <span className="reports-demo-badge">
          DEMO DATA
        </span>
      </div>

      {/* STATISTICS */}

      <div className="reports-stats">

        <div className="reports-stat-card">
          <div className="reports-stat-icon green">
            <FileText size={22} />
          </div>

          <div>
            <p>Total Reports</p>
            <h2>{reports.length}</h2>
            <span>All registered incidents</span>
          </div>
        </div>

        <div className="reports-stat-card">
          <div className="reports-stat-icon blue">
            <FileCheck size={22} />
          </div>

          <div>
            <p>Ready for Review</p>
            <h2>{readyCount}</h2>
            <span>Under investigation</span>
          </div>
        </div>

        <div className="reports-stat-card">
          <div className="reports-stat-icon orange">
            <CalendarDays size={22} />
          </div>

          <div>
            <p>Draft Reports</p>
            <h2>{draftCount}</h2>
            <span>Pending review</span>
          </div>
        </div>

        <div className="reports-stat-card">
          <div className="reports-stat-icon red">
            <AlertTriangle size={22} />
          </div>

          <div>
            <p>High Priority</p>
            <h2>{highRiskCount}</h2>
            <span>Require attention</span>
          </div>
        </div>

      </div>

      {/* REPORTS SECTION */}

      <div className="reports-section">

        <div className="reports-section-heading">
          <div>
            <h2>Investigation Records</h2>
            <p>
              Browse and access generated investigation reports.
            </p>
          </div>

          <span className="reports-count">
            {filteredReports.length} Reports
          </span>
        </div>

        {/* FILTERS */}

        <div className="reports-toolbar">

          <div className="reports-search">
            <Search size={18} />

            <input
              type="text"
              placeholder="Search report ID, incident or location..."
              value={search}
              onChange={(e) => setSearch(e.target.value)}
            />
          </div>

          <div className="reports-filter">
            <Filter size={17} />

            <select
              value={statusFilter}
              onChange={(e) => setStatusFilter(e.target.value)}
            >
              <option value="All">All Status</option>
              <option value="Ready">Ready</option>
              <option value="Draft">Draft</option>
            </select>
          </div>

          <div className="reports-filter">
            <select
              value={riskFilter}
              onChange={(e) => setRiskFilter(e.target.value)}
            >
              <option value="All">All Risk Levels</option>
              <option value="High">High Risk</option>
              <option value="Medium">Medium Risk</option>
              <option value="Low">Low Risk</option>
            </select>
          </div>

        </div>

        {/* REPORT CARDS */}

        <div className="reports-grid">

          {filteredReports.length > 0 ? (

            filteredReports.map((report) => (

              <div className="report-card" key={report.id}>

                <div className="report-card-top">

                  <div className="report-icon">
                    <FileText size={23} />
                  </div>

                  <span
                    className={`report-status ${
                      report.status === "Ready"
                        ? "report-ready"
                        : "report-draft"
                    }`}
                  >
                    {report.status}
                  </span>

                </div>

                <div className="report-card-title">
                  <h3>{report.title}</h3>
                  <p>{report.id}</p>
                </div>

                <div className="report-information">

                  <div>
                    <ClipboardList size={15} />
                    <span>Incident: {report.incident}</span>
                  </div>

                  <div>
                    <MapPin size={15} />
                    <span>{report.location}</span>
                  </div>

                  <div>
                    <CalendarDays size={15} />
                    <span>{report.date}</span>
                  </div>

                </div>

                <div className="report-card-details">

                  <div>
                    <span>Affected Area</span>
                    <strong>{report.area} hectares</strong>
                  </div>

                  <div>
                    <span>Risk Priority</span>

                    <strong
                      className={`risk-text risk-${report.risk.toLowerCase()}`}
                    >
                      {report.risk}
                    </strong>
                  </div>

                </div>

                <div className="report-card-actions">

                  <button
                    className="report-view-btn"
                    onClick={() => setSelectedReport(report)}
                  >
                    <Eye size={16} />
                    View Report
                  </button>

                  <button
                    className="report-download-btn"
                    onClick={() => downloadReport(report)}
                    title="Download report"
                  >
                    <Download size={17} />
                  </button>

                </div>

              </div>

            ))

          ) : (

            <div className="reports-empty">
              <FileText size={35} />
              <h3>No reports found</h3>
              <p>
                Try changing your search or filter settings.
              </p>
            </div>

          )}

        </div>

      </div>

      {/* DISCLAIMER */}

      <div className="reports-notice">
        <ShieldCheck size={21} />

        <div>
          <strong>Investigation Data Notice</strong>

          <p>
            Reports are generated from demonstration incident records.
            Satellite evidence and official verification documents
            are not yet integrated. Risk priority does not establish
            illegal forest activity.
          </p>
        </div>
      </div>

      {/* REPORT PREVIEW MODAL */}

      {selectedReport && (

        <div
          className="report-modal-overlay"
          onClick={() => setSelectedReport(null)}
        >

          <div
            className="report-modal"
            onClick={(e) => e.stopPropagation()}
          >

            <div className="report-modal-header">

              <div>
                <span>FORENSIQ INVESTIGATION RECORD</span>
                <h2>Report Preview</h2>
              </div>

              <button
                className="report-modal-close"
                onClick={() => setSelectedReport(null)}
              >
                <X size={21} />
              </button>

            </div>

            <div className="report-modal-body">

              <div className="report-preview-title">
                <div className="report-icon">
                  <FileText size={25} />
                </div>

                <div>
                  <h3>{selectedReport.title}</h3>
                  <p>{selectedReport.id}</p>
                </div>
              </div>

              <div className="report-preview-status">

                <span>
                  {selectedReport.status}
                </span>

                <span className={`risk-text risk-${selectedReport.risk.toLowerCase()}`}>
                  {selectedReport.risk} Priority
                </span>

              </div>

              <h4>Incident Information</h4>

              <div className="report-preview-grid">

                <div>
                  <span>Incident ID</span>
                  <strong>{selectedReport.incident}</strong>
                </div>

                <div>
                  <span>Location</span>
                  <strong>{selectedReport.location}</strong>
                </div>

                <div>
                  <span>Detection Date</span>
                  <strong>{selectedReport.date}</strong>
                </div>

                <div>
                  <span>Affected Area</span>
                  <strong>{selectedReport.area} hectares</strong>
                </div>

                <div>
                  <span>Latitude</span>
                  <strong>{selectedReport.latitude ?? "Not available"}</strong>
                </div>

                <div>
                  <span>Longitude</span>
                  <strong>{selectedReport.longitude ?? "Not available"}</strong>
                </div>

                <div>
                  <span>Investigation Status</span>
                  <strong>{selectedReport.investigationStatus}</strong>
                </div>

              </div>

              <h4>Recommended Investigation Steps</h4>

              <div className="report-preview-steps">

                <p>01. Review the reported disturbance location.</p>
                <p>02. Examine available satellite imagery.</p>
                <p>03. Verify the affected forest area.</p>
                <p>04. Check available clearance records.</p>
                <p>05. Conduct authorised manual verification.</p>

              </div>

              <div className="report-preview-disclaimer">
                <AlertTriangle size={18} />

                <p>
                  This is a demonstration report. Risk priority
                  indicates investigation urgency and does not
                  prove illegal forest activity.
                </p>
              </div>

            </div>

            <div className="report-modal-footer">

              <button
                className="report-modal-cancel"
                onClick={() => setSelectedReport(null)}
              >
                Close
              </button>

              <button
                className="report-modal-download"
                onClick={() => downloadReport(selectedReport)}
              >
                <Download size={17} />
                Download Report
              </button>

            </div>

          </div>

        </div>

      )}

    </div>
  );
}

export default Reports;